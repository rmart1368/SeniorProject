"""Build and install ChompEDR CLI, collectors and localhost dashboard on Linux."""
import argparse
import os
from pathlib import Path
import sys
import shutil
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
DASHBOARD_DIR = Path("/usr/local/lib/chomp-edr/dashboard")
DASHBOARD_UNIT = Path("/etc/systemd/system/chompedr-dashboard.service")
BINARY_PATH = Path("/usr/local/lib/chomp-edr/chompedr")
CLI_PATH = Path("/usr/local/bin/chompedr")
UNIT_DIR = Path("/etc/systemd/system")
DEFAULT_PATHS = ["/etc/passwd", "/etc/shadow", "/etc/group", "/etc/gshadow"]
SERVICES = ["chompedr-ssh.service", "chompedr-processes.service", "chompedr-files.service"]


def watch_path(value):
    path = Path(value)
    if not path.is_absolute() or ".." in path.parts:
        raise ValueError("Watched paths must be absolute without parent components")
    if any(ord(c) < 32 or ord(c) == 127 or c in '\\\"$%' for c in value):
        raise ValueError("Watched paths cannot contain control characters, backslash, quote, dollar, or percent")
    return str(path)


def units(paths):
    selected = list(dict.fromkeys(watch_path(p) for p in paths))
    if not 1 <= len(selected) <= 64:
        raise ValueError("Select 1..64 watched paths")
    commands = [
        ("ssh", "SSH journal monitor", "monitor --checkpoint /var/lib/chomp-edr/ssh"),
        ("processes", "process monitor", "watch-processes --include-existing"),
        ("files", "file metadata monitor", "watch-files " + " ".join('--path "' + p + '"' for p in selected)),
    ]
    result = {}
    for name, description, arguments in commands:
        state = "StateDirectory=chomp-edr\nStateDirectoryMode=0700\n" if name == "ssh" else ""
        result["chompedr-" + name + ".service"] = f"""# Generated by install-linux.py
[Unit]
Description=Chomp EDR {description}
PartOf=chompedr.target
After=systemd-journald.service
StartLimitIntervalSec=0

[Service]
Type=simple
User=root
ExecStart={BINARY_PATH} {arguments}
Restart=always
RestartSec=10s
KillMode=control-group
TimeoutStopSec=15s
UMask=0077
NoNewPrivileges=yes
PrivateTmp=no
StandardOutput=journal
StandardError=journal
{state}"""
    result["chompedr.target"] = """# Generated by install-linux.py
[Unit]
Description=Chomp EDR background collectors
Wants=chompedr-ssh.service chompedr-processes.service chompedr-files.service

[Install]
WantedBy=multi-user.target
"""
    return result


def regular_destination(path, replace):
    # Check parents as well: root installation must not follow redirected directories.
    for candidate in [path, *path.parents]:
        if candidate.is_symlink():
            raise ValueError(f"Refusing symlink destination or parent: {candidate}")
    if path.exists() and (not path.is_file() or not replace):
        raise ValueError(f"Destination exists or is not regular: {path}; stop collectors and use --replace to upgrade")


def atomic_write(path, data, mode):
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = None
    try:
        with tempfile.NamedTemporaryFile(dir=path.parent, prefix=".chomp-system-", delete=False) as output:
            temporary = output.name
            output.write(data)
            output.flush()
            os.fchmod(output.fileno(), mode)
            os.fsync(output.fileno())
        os.replace(temporary, path)
        temporary = None
    finally:
        if temporary is not None:
            os.unlink(temporary)


def collector_files(binary, paths, destdir=None, replace=False):
    if sys.platform != "linux":
        raise ValueError("System services require Linux with systemd")
    if destdir is None and os.geteuid() != 0:
        raise ValueError("Run with sudo for a system installation, or --destdir for staging")
    root = Path("/") if destdir is None else Path(destdir).absolute()
    source = Path(binary).resolve(strict=True)
    if not source.is_file() or not os.access(source, os.X_OK):
        raise ValueError("Build an executable with cargo build --release --locked first")
    data = source.read_bytes()
    if not data.startswith(b"\x7fELF"):
        raise ValueError("Expected a native Linux ELF executable; build on the target Linux architecture")
    generated = units(paths)
    launcher = f'#!/bin/sh\nexec "{BINARY_PATH}" "$@"\n'.encode()
    destinations = [(root / BINARY_PATH.relative_to("/"), data, 0o755),
                    (root / CLI_PATH.relative_to("/"), launcher, 0o755)]
    destinations += [(root / UNIT_DIR.relative_to("/") / name, text.encode(), 0o644)
                     for name, text in generated.items()]
    for path, _, _ in destinations:
        regular_destination(path, replace)
        if path == source:
            raise ValueError("Source and installed binary must differ")
    return destinations


def dashboard_unit(port):
    if not 1024 <= port <= 65535:
        raise ValueError("Port must be 1024..65535")
    return f"""# Generated by install-linux.py
[Unit]
Description=Chomp EDR local web dashboard
After=systemd-journald.service
StartLimitIntervalSec=0

[Service]
Type=simple
DynamicUser=yes
SupplementaryGroups=systemd-journal
ExecStart=/usr/bin/python3 {DASHBOARD_DIR}/server.py --binary {BINARY_PATH} --port {port}
Restart=always
RestartSec=10s
KillMode=control-group
TimeoutStopSec=15s
UMask=0077
NoNewPrivileges=yes
PrivateTmp=yes
ProtectSystem=strict
ProtectHome=yes
RestrictAddressFamilies=AF_INET AF_UNIX
Environment=PYTHONDONTWRITEBYTECODE=1
StandardOutput=journal
StandardError=journal

[Install]
WantedBy=multi-user.target
"""


def dashboard_files(port=8765, replace=False, destdir=None):
    if sys.platform != "linux":
        raise ValueError("The dashboard service requires Linux with systemd")
    if destdir is None and os.geteuid() != 0:
        raise ValueError("Use sudo for installation, or --destdir for staging")
    generated = dashboard_unit(port)
    stage = Path("/") if destdir is None else Path(destdir).absolute()
    sources = ["server.py", "web/index.html", "web/app.js", "web/style.css"]
    destinations = [(stage / DASHBOARD_DIR.relative_to("/") / name,
                     (ROOT / "dashboard" / name).read_bytes(), 0o644) for name in sources]
    destinations.append((stage / DASHBOARD_UNIT.relative_to("/"), generated.encode(), 0o644))
    for path, _, _ in destinations:
        regular_destination(path, replace)
    return destinations

def installation_files(binary, paths, destdir=None, replace=False, port=8765):
    files = collector_files(binary, paths, destdir, replace)
    files += dashboard_files(port, replace, destdir)
    return files


def apply_files(files, destdir=None):
    root = Path("/") if destdir is None else Path(destdir).absolute()
    # The dashboard's temporary user must be able to traverse these directories.
    for relative in [DASHBOARD_DIR.parent.relative_to("/"), DASHBOARD_DIR.relative_to("/"),
                     DASHBOARD_DIR.relative_to("/") / "web"]:
        directory = root / relative
        directory.mkdir(parents=True, exist_ok=True)
        directory.chmod(0o755)
    for path, content, mode in files:
        atomic_write(path, content, mode)
    return [path for path, _, _ in files]


def install(binary, paths=None, destdir=None, replace=False, port=8765):
    """Install all components; service activation is handled only by main."""
    files = installation_files(binary, paths or DEFAULT_PATHS, destdir, replace, port)
    return apply_files(files, destdir)


def migrate_user_install():
    """Replace only a recognized legacy user CLI with a launcher to the one system binary."""
    old = Path.home() / ".local/bin/chompedr"
    if old.is_symlink() or not old.is_file():
        return
    probe = subprocess.run([str(old), "--version"], capture_output=True, text=True, timeout=10)
    if probe.returncode != 0 or not probe.stdout.startswith("chompedr "):
        print(f"Leaving unrecognized executable untouched: {old}", file=sys.stderr)
        return
    atomic_write(old, f'#!/bin/sh\nexec "{BINARY_PATH}" "$@"\n'.encode(), 0o755)
    print(f"Updated legacy user command to launch {BINARY_PATH}")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--binary", type=Path, help="Use an existing native binary instead of building")
    parser.add_argument("--watch-path", action="append", help="Absolute watched path; repeat to override account files")
    parser.add_argument("--replace", action="store_true", help="Upgrade an existing installation")
    parser.add_argument("--port", type=int, default=8765, help="Dashboard localhost port")
    parser.add_argument("--destdir", type=Path, help="Stage files only; requires --binary; never builds or starts services")
    parser.add_argument("--no-start", action="store_true", help="Install without enabling or starting services")
    args = parser.parse_args()
    if sys.platform != "linux":
        parser.error("Installation requires Linux with systemd")
    if not 1024 <= args.port <= 65535:
        parser.error("--port must be 1024..65535")
    if args.destdir is not None and args.binary is None:
        parser.error("--destdir requires --binary")
    binary = args.binary
    if binary is None:
        packaged = ROOT / "chompedr"
        if packaged.is_file():
            binary = packaged
        else:
            if os.geteuid() == 0:
                parser.error("Run without sudo to build as your user, or supply --binary to install a prebuilt executable")
            cargo = shutil.which("cargo")
            if cargo is None:
                cargo = str(Path(os.environ.get("CARGO_HOME", str(Path.home() / ".cargo"))) / "bin/cargo")
            # Use one known native output directory, independent of caller Cargo settings.
            environment = dict(os.environ)
            environment.pop("CARGO_BUILD_TARGET", None)
            subprocess.run([cargo, "build", "--release", "--locked", "--target-dir", str(ROOT / "target")],
                           cwd=ROOT, env=environment, check=True)
            binary = ROOT / "target/release/chompedr"
    binary = binary.resolve(strict=True)
    if args.destdir is None and os.geteuid() != 0:
        if not shutil.which("sudo"):
            parser.error("sudo is required for system installation")
        forwarded = ["sudo", "python3", str(Path(__file__).resolve()), "--binary", str(binary),
                     "--port", str(args.port)]
        if args.replace:
            forwarded.append("--replace")
        if args.no_start:
            forwarded.append("--no-start")
        for path in args.watch_path or []:
            forwarded.extend(["--watch-path", path])
        subprocess.run(forwarded, check=True)
        migrate_user_install()
        return
    if args.destdir is None and not shutil.which("systemctl"):
        parser.error("systemctl is required")
    files = installation_files(binary, args.watch_path or DEFAULT_PATHS,
                               args.destdir, args.replace, args.port)
    if args.destdir is None and args.replace:
        # Validate the complete installation before stopping any running service.
        existing = [name for name in ("chompedr-dashboard.service", "chompedr.target")
                    if (UNIT_DIR / name).exists()]
        if existing:
            subprocess.run(["systemctl", "stop", *existing], check=True)
    for path in apply_files(files, args.destdir):
        print(f"Installed {path}")
    if args.destdir is not None:
        print("Staged only. No services enabled or started.")
        return
    subprocess.run(["systemctl", "daemon-reload"], check=True)
    if not args.no_start:
        subprocess.run(["systemctl", "enable", "--now", "chompedr.target", "chompedr-dashboard.service"], check=True)
        for name in [*SERVICES, "chompedr-dashboard.service"]:
            subprocess.run(["systemctl", "is-active", "--quiet", name], check=True)
        print("Collectors and dashboard are running.")
    print("CLI: chompedr (open a new terminal or run hash -r if your shell cached an old path)")
    print(f"Dashboard: http://127.0.0.1:{args.port}")
    print("If /usr/local/bin is missing from PATH, add it in your shell configuration.")
    print("Legacy per-user binaries can shadow this installation; inspect with: type -a chompedr")


if __name__ == "__main__":
    try:
        main()
    except (OSError, ValueError, subprocess.SubprocessError) as error:
        print(f"Install failed: {error}", file=sys.stderr)
        sys.exit(1)
